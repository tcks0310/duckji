function H({ children }: { children: React.ReactNode }) {
  return <h3 className="text-sm font-bold text-white pt-2">{children}</h3>
}

function P({ children }: { children: React.ReactNode }) {
  return <p className="text-zinc-400">{children}</p>
}

function UL({ items }: { items: React.ReactNode[] }) {
  return (
    <ul className="pl-4 list-disc list-outside space-y-1 text-zinc-400">
      {items.map((item, i) => (
        <li key={i}>{item}</li>
      ))}
    </ul>
  )
}

function Table({ head, rows }: { head: string[]; rows: React.ReactNode[][] }) {
  return (
    <div className="overflow-x-auto">
      <table className="w-full text-left text-zinc-400 border border-zinc-800">
        <thead className="bg-zinc-900 text-zinc-300">
          <tr>
            {head.map((h) => (
              <th key={h} className="px-2 py-1.5 border border-zinc-800 font-bold">
                {h}
              </th>
            ))}
          </tr>
        </thead>
        <tbody>
          {rows.map((row, i) => (
            <tr key={i}>
              {row.map((cell, j) => (
                <td key={j} className="px-2 py-1.5 border border-zinc-800 align-top">
                  {cell}
                </td>
              ))}
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  )
}

